"""
Pure-Python reimplementation (standard library only) of the group-theoretic
logic in generate_groups_sage.py, used to check that logic without Sage or
GAP.

Groups are represented by explicit multiplication tables, so every operation
below uses only table lookups and set operations, which can be checked by hand.
"""

import itertools

class Grp:
    def __init__(self, n, mul, name):
        self.n = n
        self.mul = mul                      # mul[a][b] = a*b, 0-indexed
        self.name = name
        self.elements = list(range(n))
        self.e = next(x for x in range(n) if all(mul[x][y] == y and mul[y][x] == y for y in range(n)))
        self.inv = [next(y for y in range(n) if mul[x][y] == self.e) for x in range(n)]
        self._check_axioms()

    def _check_axioms(self):
        for a, b, c in itertools.product(self.elements, repeat=3):
            assert self.mul[self.mul[a][b]][c] == self.mul[a][self.mul[b][c]], "not associative!"

    def op(self, *xs):
        r = self.e
        for x in xs:
            r = self.mul[r][x]
        return r

    def order_of(self, x):
        y, k = x, 1
        while y != self.e:
            y = self.mul[y][x]
            k += 1
        return k

    def commutator(self, x, y):
        return self.op(self.inv[x], self.inv[y], x, y)

    def centralizer(self, x):
        return [g for g in self.elements if self.mul[g][x] == self.mul[x][g]]

    def conjugacy_class(self, x):
        return sorted({self.op(g, x, self.inv[g]) for g in self.elements})

    def conjugacy_classes(self):
        seen, classes = set(), []
        for x in self.elements:
            if x in seen:
                continue
            c = self.conjugacy_class(x)
            classes.append(c)
            seen.update(c)
        return classes

    def center(self):
        return [x for x in self.elements if len(self.centralizer(x)) == self.n]

    def closure(self, gens):
        S = set(gens) | {self.e}
        changed = True
        while changed:
            changed = False
            for a, b in itertools.product(list(S), list(S)):
                p = self.mul[a][b]
                if p not in S:
                    S.add(p)
                    changed = True
        return S

    def derived_subgroup(self):
        gens = {self.commutator(x, y) for x, y in itertools.product(self.elements, repeat=2)}
        return self.closure(gens)

    def is_abelian(self):
        return all(self.mul[a][b] == self.mul[b][a] for a, b in itertools.product(self.elements, repeat=2))

    def derived_length(self):
        Gi = set(self.elements)
        length = 0
        while len(Gi) != 1:
            gens = {self.commutator(x, y) for x in Gi for y in Gi}
            Gi_next = self.closure(gens)
            if Gi_next == Gi:
                break
            Gi = Gi_next
            length += 1
        return length

    def exponent(self):
        from math import gcd
        lcm = 1
        for x in self.elements:
            o = self.order_of(x)
            lcm = lcm * o // gcd(lcm, o)
        return lcm

    def nilpotency_class(self):
        # returns 1 for every abelian group, including the trivial group
        gamma = set(self.elements)
        c = 1
        while len(gamma) != 1:
            new_gens = {self.op(self.inv[x], self.inv[y], x, y) for x in gamma for y in self.elements}
            gamma_next = self.closure(new_gens)
            if len(gamma_next) == len(gamma):
                break
            gamma = gamma_next
            if len(gamma) != 1:
                c += 1
        return c

    def _power(self, g, e):
        """g^e via repeated multiplication (e small in all our test cases)."""
        x = self.e
        for _ in range(e):
            x = self.mul[x][g]
        return x

    def power_subgroup_correct(self, k, p=2):
        """Return G^(p^k), the subgroup generated by g^(p^k) for every
        element g of G, not only for a generating set."""
        powers = {self._power(g, p ** k) for g in self.elements}
        return self.closure(powers)

    def power_subgroup_from_generators(self, k, gens, p=2):
        """Return the subgroup generated by g^(p^k) for g in gens, rather
        than for every element of G. For irregular p-groups this need not
        equal G^(p^k). test_group_theory.py compares it with
        power_subgroup_correct on the fixture."""
        current_gens = set(gens)
        for _ in range(k):
            current_gens = {self._power(g, p) for g in current_gens}
        return self.closure(current_gens)

    def is_powerful(self, p=2):
        """G is powerful if [G,G] <= G^p (p odd) or [G,G] <= G^4 (p=2)."""
        GG = self.derived_subgroup()
        Gk = self.power_subgroup_correct(2, p=2) if p == 2 else self.power_subgroup_correct(1, p=p)
        return GG.issubset(Gk)

    def is_powerful_p2(self):
        """Convenience specialization of is_powerful to p=2."""
        return self.is_powerful(p=2)

    def upper_powerfully_central_series(self, p=2, max_len=10):
        Zhat = [set([self.e])]
        for _ in range(max_len):
            prev = Zhat[-1]
            prev_p = self.closure({self._power(a, p) for a in prev})
            nxt = {a for a in self.elements
                   if all(self.commutator(a, x) in prev_p for x in self.elements)}
            if nxt == prev:
                break
            Zhat.append(nxt)
        return Zhat

    def powerful_class(self, p=2):
        if not self.is_powerful(p=p):
            return None
        series = self.upper_powerfully_central_series(p=p)
        for i, S in enumerate(series):
            if len(S) == self.n:
                return i
        return None  # series did not reach G (possible for a powerful group when p is odd)


def cyclic(n):
    mul = [[(a + b) % n for b in range(n)] for a in range(n)]
    return Grp(n, mul, f"C{n}")


def semidirect_zn_zk(n, k, m, name=None):
    """Z_n rtimes Z_k via b a b^-1 = a^m (need m^k = 1 mod n).
    Elements encoded as i*k+s for i in Z_n, s in Z_k."""
    assert pow(m, k, n) == 1 % n
    N = n * k

    def decode(x):
        return x // k, x % k

    def encode(i, s):
        return (i % n) * k + (s % k)

    mul = [[0] * N for _ in range(N)]
    for x in range(N):
        i, s = decode(x)
        for y in range(N):
            j, t = decode(y)
            mult = pow(m, s, n)
            mul[x][y] = encode((i + mult * j) % n, (s + t) % k)
    return Grp(N, mul, name or f"Zn_zk_{n}_{k}_{m}")


def semidirect_zn_z2(n, m, name=None):
    """Z_n rtimes Z_2 via b a b^-1 = a^m (need m^2 = 1 mod n). Typical choices:
    m=1          gives C_n x C_2
    m=n-1        gives the dihedral group D_{2n}
    m=1+n//2     gives the modular group M_{2n} (n a power of 2, n>=8)
    m=n//2-1     gives the semidihedral group SD_{2n} (n a power of 2, n>=8)
    """
    return semidirect_zn_zk(n, 2, m, name)


def direct_product(G, H):
    n = G.n * H.n
    def enc(a, b):
        return a * H.n + b
    mul = [[0]*n for _ in range(n)]
    for a1 in range(G.n):
        for b1 in range(H.n):
            for a2 in range(G.n):
                for b2 in range(H.n):
                    mul[enc(a1,b1)][enc(a2,b2)] = enc(G.mul[a1][a2], H.mul[b1][b2])
    return Grp(n, mul, f"{G.name}x{H.name}")


def quaternion8():
    # elements: 0=1,1=-1,2=i,3=-i,4=j,5=-j,6=k,7=-k
    names = ['1','-1','i','-i','j','-j','k','-k']
    def val(s):
        sign = 1
        if s.startswith('-'):
            sign, s = -1, s[1:]
        base = {'1': (1,0,0,0), 'i': (0,1,0,0), 'j': (0,0,1,0), 'k': (0,0,0,1)}[s]
        return tuple(sign*c for c in base)
    def qmul(p, q):
        a1,b1,c1,d1 = p
        a2,b2,c2,d2 = q
        a = a1*a2 - b1*b2 - c1*c2 - d1*d2
        b = a1*b2 + b1*a2 + c1*d2 - d1*c2
        c = a1*c2 - b1*d2 + c1*a2 + d1*b2
        d = a1*d2 + b1*c2 - c1*b2 + d1*a2
        return (a,b,c,d)
    vals = [val(s) for s in names]
    lookup = {v: idx for idx, v in enumerate(vals)}
    mul = [[lookup[qmul(vals[x], vals[y])] for y in range(8)] for x in range(8)]
    return Grp(8, mul, "Q8")


def heisenberg_group(p):
    """Heisenberg group over F_p: upper unitriangular 3x3 matrices,
    equivalently triples (a,b,c) in Z_p^3 with
    (a,b,c)*(a',b',c') = (a+a', b+b', c+c'+a*b') mod p.
    Order p^3, exponent p for odd p (extraspecial, non-abelian)."""
    def enc(a, b, c):
        return (a % p) * p * p + (b % p) * p + (c % p)
    N = p ** 3
    mul = [[0] * N for _ in range(N)]
    for x in range(N):
        a, b, c = x // (p * p), (x // p) % p, x % p
        for y in range(N):
            a2, b2, c2 = y // (p * p), (y // p) % p, y % p
            mul[x][y] = enc(a + a2, b + b2, c + c2 + a * b2)
    return Grp(N, mul, f"Heis{p}")


def to_dataset_json_entry(G, group_id, p=2):
    """Return one group entry as a dict in the format produced by
    generate_groups_sage.py, which dataset.py reads."""
    elements = G.elements
    index_map = {x: i for i, x in enumerate(elements)}
    Z = set(G.center())
    classes = G.conjugacy_classes()
    class_size = {}
    for c in classes:
        for x in c:
            class_size[x] = len(c)

    # pdepth(x) is the largest k with x in G^(p^k). Each level that contains x
    # overwrites pdepth(x), so the identity gets pdepth m, where m is the first
    # level with G^(p^m) = {1}, that is m = log_p(exponent).
    pdepth = {}
    k = 0
    current = set(elements)
    while True:
        for x in current:
            pdepth[x] = k
        if len(current) == 1:
            break
        k += 1
        nxt = G.power_subgroup_correct(k, p=p)
        if nxt == current:
            break  # series stalled, which cannot happen for a finite p-group
        current = nxt

    node_features = []
    for x in elements:
        node_features.append([
            G.order_of(x),
            len(G.centralizer(x)),
            class_size[x],
            1 if x in Z else 0,
            pdepth.get(x, 0),
        ])

    edges = []
    for ix, x in enumerate(elements):
        for y in G.centralizer(x):
            if y != x and ix < index_map[y]:
                edges.append([ix, index_map[y]])
    bidir_edges = edges + [[b, a] for a, b in edges]

    powerful = G.is_powerful(p=p)
    pclass = G.powerful_class(p=p)
    n_exp = round(__import__("math").log(G.n, p))  # G.n = p^n_exp

    return {
        "order": G.n,
        "prime": p,
        "group_id": group_id,
        "num_nodes": len(elements),
        "edges": bidir_edges,
        "node_features": node_features,
        "invariants": {
            "nilpotency_class": G.nilpotency_class(),
            "derived_length": G.derived_length(),
            "center_size": len(Z),
            "commutator_size": len(G.derived_subgroup()),
            "num_conj_classes": len(classes),
            "exponent": G.exponent(),
            "is_powerful": bool(powerful),
            "powerful_class": pclass,
            "powerful_coclass": (n_exp - pclass) if pclass is not None else None,
        },
    }


